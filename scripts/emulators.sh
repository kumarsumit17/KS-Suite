#!/bin/sh
# Android phone and Google TV emulators for testing the KS-Suite apps on this Mac.
# See specs/testing.md. Development tool only; nothing here is shipped.
#
#   scripts/emulators.sh create          # create the two AVDs (once)
#   scripts/emulators.sh create-sizes    # create one Google TV AVD per screen size (once)
#   scripts/emulators.sh sizes           # the TV screen sizes: tv-32 tv-43 ... tv-100
#   scripts/emulators.sh start phone|tv|tv-55  # boot one (add --headless for no window) and wait
#   scripts/emulators.sh stop  phone|tv|tv-55  # shut it down
#   scripts/emulators.sh list            # AVDs and running devices
#   scripts/emulators.sh serial phone|tv|tv-55 # adb serial of the running one (for adb -s / ANDROID_SERIAL)
#
# Needs: the SDK packages emulator, platform-tools,
#   system-images;android-36;google_apis;arm64-v8a and system-images;android-36;android-tv;arm64-v8a
set -eu

SDK="${ANDROID_HOME:-${ANDROID_SDK_ROOT:-/opt/homebrew/share/android-commandlinetools}}"
AVDMANAGER="$SDK/cmdline-tools/latest/bin/avdmanager"
EMULATOR="$SDK/emulator/emulator"
ADB="$SDK/platform-tools/adb"
export ANDROID_HOME="$SDK" ANDROID_SDK_ROOT="$SDK"

PHONE_AVD=ks-phone-36
TV_AVD=ks-tv-36
PHONE_PORT=5554   # adb serial emulator-5554
TV_PORT=5556      # adb serial emulator-5556

# Google TV screen sizes (specs/testing.md, "TV screen sizes"): inches:width:height:density.
# The resolution is what TVs of that size usually have; the density is the one Android TV
# uses for that resolution (720p 213, 1080p 320, 4K 640), so every size lays out the same
# 960x540 dp, and the diagonal gives each its true physical pixels per inch (xdpi/ydpi).
TV_SIZES="32:1280:720:213 43:1920:1080:320 50:3840:2160:640 55:3840:2160:640 65:3840:2160:640 75:3840:2160:640 85:3840:2160:640 100:3840:2160:640"
TV_SIZE_PORT=5560 # tv-32 is emulator-5560, the next size +2, and so on

size_field() { # inch field(1-4)
  for e in $TV_SIZES; do [ "${e%%:*}" = "$1" ] && { echo "$e" | cut -d: -f"$2"; return; }; done
  echo "no TV size '$1' (sizes: $(sizes))" >&2; exit 2
}
sizes() { for e in $TV_SIZES; do printf 'tv-%s ' "${e%%:*}"; done; echo; }
size_port() { i=0; for e in $TV_SIZES; do [ "${e%%:*}" = "$1" ] && { echo $((TV_SIZE_PORT + 2 * i)); return; }; i=$((i + 1)); done; size_field "$1" 1 >/dev/null; }

avd_of() { case "$1" in phone) echo "$PHONE_AVD" ;; tv) echo "$TV_AVD" ;; tv-*) size_field "${1#tv-}" 1 >/dev/null; echo "ks-tv-${1#tv-}in" ;; *) echo "phone, tv or tv-<inches>, not '$1'" >&2; exit 2 ;; esac; }
port_of() { case "$1" in phone) echo "$PHONE_PORT" ;; tv) echo "$TV_PORT" ;; tv-*) size_port "${1#tv-}" ;; esac; }

DEVICES_XML="$HOME/.android/devices.xml"
DEVICES_MARK="ks-suite: generated by scripts/emulators.sh"

# Writes one device definition per TV size to ~/.android/devices.xml (where avdmanager
# reads user devices). Never overwrites a devices.xml this script did not write.
write_devices() {
  if [ -f "$DEVICES_XML" ] && ! grep -q "$DEVICES_MARK" "$DEVICES_XML"; then
    echo "$DEVICES_XML exists and was not written by this script; add the ks_tv_* devices by hand" >&2; return 1
  fi
  mkdir -p "$HOME/.android"
  {
    printf '<?xml version="1.0" encoding="UTF-8"?>\n<!-- %s -->\n' "$DEVICES_MARK"
    printf '<d:devices xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" xmlns:d="http://schemas.android.com/sdk/devices/1">\n'
    for e in $TV_SIZES; do
      IFS=: read -r inch w h dens <<EOT
$e
EOT
      case "$dens" in 213) bucket=tvdpi ;; 320) bucket=xhdpi ;; *) bucket=xxxhdpi ;; esac
      ppi=$(awk -v w="$w" -v h="$h" -v d="$inch" 'BEGIN { printf "%.2f", sqrt(w*w + h*h) / d }')
      cat <<EOT
  <d:device>
    <d:name>KS Google TV ${inch} inch (${w}x${h})</d:name>
    <d:id>ks_tv_${inch}</d:id>
    <d:manufacturer>KS-Suite</d:manufacturer>
    <d:hardware>
      <d:screen>
        <d:screen-size>xlarge</d:screen-size>
        <d:diagonal-length>${inch}.0</d:diagonal-length>
        <d:pixel-density>${bucket}</d:pixel-density>
        <d:screen-ratio>long</d:screen-ratio>
        <d:dimensions><d:x-dimension>${w}</d:x-dimension><d:y-dimension>${h}</d:y-dimension></d:dimensions>
        <d:xdpi>${ppi}</d:xdpi>
        <d:ydpi>${ppi}</d:ydpi>
        <d:touch><d:multitouch>none</d:multitouch><d:mechanism>notouch</d:mechanism><d:screen-type>notouch</d:screen-type></d:touch>
      </d:screen>
      <d:networking>Wifi</d:networking>
      <d:sensors/>
      <d:mic>true</d:mic>
      <d:keyboard>qwerty</d:keyboard>
      <d:nav>dpad</d:nav>
      <d:ram unit="GiB">2</d:ram>
      <d:buttons>hard</d:buttons>
      <d:internal-storage unit="GiB">8</d:internal-storage>
      <d:removable-storage unit="MiB">0</d:removable-storage>
      <d:cpu>Generic CPU</d:cpu>
      <d:gpu>Generic GPU</d:gpu>
      <d:abi>armeabi-v7a x86</d:abi>
      <d:dock/>
      <d:power-type>plugged-in</d:power-type>
    </d:hardware>
    <d:software>
      <d:api-level>21-</d:api-level>
      <d:live-wallpaper-support>true</d:live-wallpaper-support>
      <d:bluetooth-profiles/>
      <d:gl-version>2.0</d:gl-version>
      <d:gl-extensions/>
      <d:status-bar>false</d:status-bar>
    </d:software>
    <d:state name="Landscape" default="true">
      <d:description>Landscape</d:description>
      <d:screen-orientation>land</d:screen-orientation>
      <d:keyboard-state>keyshidden</d:keyboard-state>
      <d:nav-state>navexposed</d:nav-state>
    </d:state>
    <d:tag-id>android-tv</d:tag-id>
  </d:device>
EOT
    done
    printf '</d:devices>\n'
  } >"$DEVICES_XML"
}

has_avd() { "$EMULATOR" -list-avds 2>/dev/null | grep -qx "$1"; }

# The AVD running on an adb serial, or nothing when no emulator is there. Another app's
# own AVD can hold one of our fixed ports, so every command checks the name before it
# uses a serial: it never reports or stops an emulator that is not the one asked for.
avd_on() { # serial
  "$ADB" devices | grep -q "^$1[[:space:]]" || return 0
  "$ADB" -s "$1" emu avd name 2>/dev/null | head -n 1 | tr -d '\r'
}
check_port() { # serial avd; fails when another AVD holds the port
  on=$(avd_on "$1")
  [ -z "$on" ] || [ "$on" = "$2" ] && return 0
  echo "$1 is AVD '$on', not $2: another emulator holds port ${1#emulator-}. Stop that one first (adb -s $1 emu kill, if it is yours) or use another size." >&2
  return 1
}

create_one() { # name image device
  if has_avd "$1"; then echo "$1: exists"; return; fi
  [ -f "$SDK/$(echo "$2" | tr ";" "/")/package.xml" ] || { echo "missing SDK package: $2 (sdkmanager \"$2\")" >&2; return 1; }
  echo no | "$AVDMANAGER" create avd -n "$1" -k "$2" -d "$3" >/dev/null 2>"${TMPDIR:-/tmp}/avdmanager-$1.log" || true
  [ -f "$HOME/.android/avd/$1.avd/config.ini" ] || { echo "$1: avdmanager failed (log: ${TMPDIR:-/tmp}/avdmanager-$1.log)" >&2; return 1; }
  # Hardware keyboard on, so the Mac's arrow keys, Enter and Esc act as the D-pad, OK and Back.
  printf 'hw.keyboard=yes\nhw.dPad=yes\n' >> "$HOME/.android/avd/$1.avd/config.ini"
  echo "$1: created"
}

case "${1:-}" in
  create)
    rc=0
    create_one "$PHONE_AVD" "system-images;android-36;google_apis;arm64-v8a" pixel_8 || rc=1
    create_one "$TV_AVD" "system-images;android-36;android-tv;arm64-v8a" tv_1080p || rc=1
    exit "$rc"
    ;;
  create-sizes)
    write_devices
    rc=0
    for e in $TV_SIZES; do
      inch=${e%%:*}; avd=$(avd_of "tv-$inch")
      create_one "$avd" "system-images;android-36;android-tv;arm64-v8a" "ks_tv_$inch" || { rc=1; continue; }
      cfg="$HOME/.android/avd/$avd.avd/config.ini"
      # The density Android TV uses for this resolution (not computed from the inches).
      grep -v '^hw.lcd.density=' "$cfg" >"$cfg.tmp" && mv "$cfg.tmp" "$cfg"
      echo "hw.lcd.density=$(size_field "$inch" 4)" >>"$cfg"
    done
    exit "$rc"
    ;;
  sizes)
    sizes
    ;;
  start)
    which="${2:?phone, tv or tv-<inches>}"; avd=$(avd_of "$which"); port=$(port_of "$which"); serial="emulator-$port"
    extra=""; [ "${3:-}" = "--headless" ] && extra="-no-window -no-audio"
    check_port "$serial" "$avd" || exit 1
    if [ -z "$(avd_on "$serial")" ]; then
      # shellcheck disable=SC2086
      nohup "$EMULATOR" -avd "$avd" -port "$port" -no-snapshot-save -no-boot-anim $extra >"${TMPDIR:-/tmp}/$avd.log" 2>&1 &
    fi
    "$ADB" -s "$serial" wait-for-device
    check_port "$serial" "$avd" || exit 1
    i=0
    until [ "$("$ADB" -s "$serial" shell getprop sys.boot_completed 2>/dev/null | tr -d '\r')" = 1 ]; do
      i=$((i + 1)); [ "$i" -gt 180 ] && { echo "$avd did not boot in 6 minutes (log: ${TMPDIR:-/tmp}/$avd.log)" >&2; exit 1; }
      sleep 2
    done
    "$ADB" -s "$serial" shell input keyevent 82 >/dev/null 2>&1 || true   # dismiss the lock screen
    echo "$avd booted as $serial"
    ;;
  stop)
    which="${2:?phone, tv or tv-<inches>}"; avd=$(avd_of "$which"); serial="emulator-$(port_of "$which")"
    check_port "$serial" "$avd" || exit 1
    if [ -z "$(avd_on "$serial")" ]; then echo "$avd is not running"; exit 0; fi
    "$ADB" -s "$serial" emu kill >/dev/null 2>&1 || true; echo "stopped $avd ($serial)"
    ;;
  serial)
    which="${2:?phone, tv or tv-<inches>}"; avd=$(avd_of "$which"); serial="emulator-$(port_of "$which")"
    check_port "$serial" "$avd" || exit 1
    echo "$serial"
    ;;
  list)
    "$EMULATOR" -list-avds; "$ADB" devices
    ;;
  *)
    sed -n '2,14p' "$0"; exit 2
    ;;
esac
